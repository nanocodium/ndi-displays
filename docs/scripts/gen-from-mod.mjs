import { readdir, readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join, extname, basename } from 'node:path'
import { fileURLToPath } from 'node:url'

const docsRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = join(docsRoot, '..')

/** Wiki path for a block registry id. Unknown ids fall back to a kebab slug (build then fails until a page exists). */
const PAGE_BY_ID = {
  led_panel: '/blocks/led-panel',
  led_corner: '/blocks/led-panel#90-turns',
  blow_through_panel: '/blocks/blow-through-panel',
  led_floor: '/blocks/led-floor',
  kinetic_winch: '/blocks/kinetic-winch',
  chain_hoist: '/blocks/chain-hoist',
  round_screen: '/blocks/round-screen',
  curved_screen: '/blocks/curved-screen',
  multiview: '/blocks/multiview',
  winch_park_monitor: '/blocks/winch-park-monitor',
  broadcast_camera: '/blocks/cameras#broadcast-camera',
  ptz_camera: '/blocks/cameras#ptz-camera',
  jib_camera: '/blocks/cameras#jib-camera',
  track_camera: '/blocks/cameras#track-dolly',
  camera_track: '/blocks/cameras#camera-track',
  ndi_router: '/blocks/ndi-router',
  web_terminal: '/blocks/web-terminal',
  projector: '/blocks/projector',
  computer: '/blocks/computer',
  vision_switcher: '/blocks/vision-switcher',
  pro_monitor: '/blocks/pro-monitor',
  equipment_rack: '/blocks/equipment-rack'
}

function titleFromId(id) {
  return id.split('_').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join(' ')
}

function itemLabel(entry) {
  if (!entry) return '—'
  if (entry.item) return `\`${entry.item}\``
  if (entry.tag) return `#${entry.tag}`
  return JSON.stringify(entry)
}

function formatRecipe(json) {
  const result = json.result ?? {}
  const resultId = result.item ?? '?'
  const count = result.count && result.count !== 1 ? ` ×${result.count}` : ''
  if (json.type === 'minecraft:crafting_shaped') {
    const pattern = (json.pattern ?? []).join(' / ')
    const keys = Object.entries(json.key ?? {})
      .map(([k, v]) => `${k}=${itemLabel(v)}`)
      .join(', ')
    return { kind: 'shaped', pattern, keys, result: resultId + count }
  }
  if (json.type === 'minecraft:crafting_shapeless') {
    const keys = (json.ingredients ?? []).map(itemLabel).join(', ')
    return { kind: 'shapeless', pattern: '—', keys, result: resultId + count }
  }
  return { kind: json.type ?? 'unknown', pattern: '—', keys: '—', result: resultId + count }
}

async function parseBlockIds() {
  const java = await readFile(
    join(repoRoot, 'src/main/java/dev/nano/ndidisplays/NdiDisplays.java'),
    'utf8'
  )
  const ids = []
  const re = /BLOCKS\.register\("([a-z0-9_]+)"/g
  let m
  while ((m = re.exec(java)) !== null) {
    ids.push(m[1])
  }
  return ids
}

async function writeBlockCatalog(ids) {
  const rows = ids.map((id) => {
    const href = PAGE_BY_ID[id] ?? `/blocks/${id.replace(/_/g, '-')}`
    return `| \`ndidisplays:${id}\` | [${titleFromId(id)}](${href}) |`
  })
  const body = `---
title: Blocks
outline: deep
---

<!-- Generated by scripts/gen-from-mod.mjs — do not edit by hand. -->

# Blocks

Registered in \`NdiDisplays.java\` via \`BLOCKS.register("…")\` (not \`BLOCKS.register(modBus)\`).

**${ids.length}** block${ids.length === 1 ? '' : 's'} in the current source.

| Registry ID | Wiki |
|-------------|------|
${rows.join('\n')}

Creative tab: **NDI Stage Displays**. Server registers every block; NDI I/O is client-only.
`
  const out = join(docsRoot, 'blocks/index.md')
  await mkdir(dirname(out), { recursive: true })
  await writeFile(out, body, 'utf8')
}

async function writeRecipes() {
  const dir = join(repoRoot, 'src/main/resources/data/ndidisplays/recipes')
  const files = (await readdir(dir))
    .filter((f) => extname(f) === '.json')
    .sort((a, b) => a.localeCompare(b))
  const rows = []
  for (const file of files) {
    const json = JSON.parse(await readFile(join(dir, file), 'utf8'))
    const rec = formatRecipe(json)
    rows.push(
      `| \`${basename(file, '.json')}\` | ${rec.kind} | ${rec.pattern} | ${rec.keys} | \`${rec.result}\` |`
    )
  }
  const body = `---
title: Recipes
outline: deep
---

<!-- Generated by scripts/gen-from-mod.mjs — do not edit by hand. -->

# Recipes

Crafts from \`src/main/resources/data/ndidisplays/recipes/\`. This table is regenerated on every \`npm run docs:gen\` / \`docs:build\`.

**${files.length}** recipe file${files.length === 1 ? '' : 's'}.

| File | Type | Pattern | Keys / ingredients | Result |
|------|------|---------|--------------------|--------|
${rows.join('\n')}
`
  const out = join(docsRoot, 'reference/recipes.md')
  await mkdir(dirname(out), { recursive: true })
  await writeFile(out, body, 'utf8')
}

const ids = await parseBlockIds()
if (ids.length === 0) {
  throw new Error('No BLOCKS.register("id") found in NdiDisplays.java')
}
await writeBlockCatalog(ids)
await writeRecipes()
console.log(`gen-from-mod: ${ids.length} blocks, recipes written`)
