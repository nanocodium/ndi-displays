"""Builds the halogen work light assets from the source OBJ/MTL.

The mod's OBJ mesh loader (ObjPartMesh) and Forge's OBJ item loader both texture from UVs;
neither reads MTL colours. So the exporter's per-material Kd colours are baked into a small
palette texture and every face's UVs are rewritten to the centre of its material's cell. The
palette is mirrored top/bottom so that flip_v (Forge item model) and the BER's own V flip land
on the same cell.

Usage: python tools/gen_worklight_assets.py <source.obj> <source.mtl>
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
MESHES = ROOT / "src/main/resources/assets/ndidisplays/meshes"
TEXTURES = ROOT / "src/main/resources/assets/ndidisplays/textures"

# Display colours per material. The MTL blacks are near 0.01, which reads as a hole in
# Minecraft's lighting, so the dark plastics and paints are lifted to a readable charcoal.
PALETTE = {
    "body_black": (36, 36, 40),
    "frame_black": (28, 28, 31),
    "yoke_black": (33, 33, 37),
    "rubber": (22, 22, 22),
    "reflector_alu": (188, 194, 200),
    "silver": (142, 150, 160),
    "ceramic": (214, 206, 190),
    "glass": (196, 214, 222),
    "lamp_white": (255, 238, 200),
}

CELL = 8
COLS = 8
ROWS = 8  # rows 0..3 used, mirrored into 7..4


def cell_of(index):
    return index % COLS, index // COLS


def build_palette(materials, out_png):
    img = Image.new("RGBA", (COLS * CELL, ROWS * CELL), (255, 0, 255, 255))
    draw = ImageDraw.Draw(img)
    for i, name in enumerate(materials):
        cx, cy = cell_of(i)
        colour = PALETTE.get(name, (200, 200, 200)) + (255,)
        for row in (cy, ROWS - 1 - cy):
            draw.rectangle([cx * CELL, row * CELL, (cx + 1) * CELL - 1, (row + 1) * CELL - 1],
                           fill=colour)
    img.save(out_png)


def convert(obj_path, mtl_path):
    lines = Path(obj_path).read_text(encoding="utf-8").splitlines()
    materials = []
    for line in lines:
        if line.startswith("usemtl "):
            name = line.split()[1]
            if name not in materials:
                materials.append(name)
    if len(materials) > COLS * (ROWS // 2):
        raise SystemExit("too many materials for the palette")

    build_palette(materials, TEXTURES / "block" / "worklight_atlas.png")

    out = ["# Halogen work light. Generated by tools/gen_worklight_assets.py from the",
           "# three-d-stage export: UVs point into worklight_atlas.png, one cell per material.",
           "mtllib worklight.mtl"]
    vt_lines = []
    current_vt = None
    for line in lines:
        if line.startswith("mtllib"):
            continue
        if line.startswith("usemtl "):
            name = line.split()[1]
            cx, cy = cell_of(materials.index(name))
            u = (cx + 0.5) / COLS
            v = 1.0 - (cy + 0.5) / ROWS  # OBJ v is bottom-up
            vt_lines.append(f"vt {u:.5f} {v:.5f}")
            current_vt = len(vt_lines)
            out.append("usemtl atlas")
            continue
        if line.startswith("vt "):
            continue  # replaced by the per-material cells
        if line.startswith("f "):
            parts = line.split()
            face = ["f"]
            for tok in parts[1:]:
                idx = tok.split("/")
                v_i = idx[0]
                n_i = idx[2] if len(idx) > 2 else ""
                face.append(f"{v_i}/{current_vt}/{n_i}" if n_i else f"{v_i}/{current_vt}")
            out.append(" ".join(face))
            continue
        out.append(line)

    # vt must precede the faces that use them: insert after the last vertex/normal block start.
    first_face = next(i for i, l in enumerate(out) if l.startswith("f "))
    first_o = next(i for i, l in enumerate(out) if l.startswith("o "))
    insert_at = first_o
    out[insert_at:insert_at] = vt_lines
    del first_face

    (MESHES / "worklight.obj").write_text("\n".join(out) + "\n", encoding="utf-8")
    (MESHES / "worklight.mtl").write_text(
        "newmtl atlas\nKd 1.0 1.0 1.0\nmap_Kd #atlas\n", encoding="utf-8")
    print(f"materials: {materials}")
    print("wrote", MESHES / "worklight.obj")


def remote_texture():
    """Yellow belly-box with a green and a red key, the work-light switch a stage hand carries."""
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    d.rectangle([4, 1, 11, 14], fill=(46, 46, 50, 255))
    d.rectangle([5, 2, 10, 13], fill=(232, 176, 32, 255))
    d.rectangle([6, 3, 9, 5], fill=(40, 40, 44, 255))  # label window
    d.rectangle([6, 7, 9, 8], fill=(70, 200, 90, 255))   # ON
    d.rectangle([6, 10, 9, 11], fill=(210, 60, 50, 255))  # OFF
    d.point([(7, 0)], fill=(90, 90, 95, 255))  # antenna
    img.save(TEXTURES / "item" / "worklight_remote.png")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        raise SystemExit(__doc__)
    convert(sys.argv[1], sys.argv[2])
    remote_texture()
